/**
 * Generates src/generated/productionFieldMap.ts from productionTables.ts — the production twin of
 * gen-stage-map.ts. Unlike procurement (where STAGE_MODELS is hand-declared because 16 entries is
 * writable by hand), the model/spine/cardinality decision already lives ON productionTables.ts
 * itself (22 entries, data-driven since 78 flow nodes made a hand-written lookup impractical — see
 * productionStages.ts's header). This script's job is narrower: validate the same invariants
 * gen-stage-map.ts validates, then re-emit as the flat lookup map the backend/frontend consume.
 *
 * Run `npm run gen` to regenerate (runs both generators), `npm run gen:check` in CI to fail on
 * drift.
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { productionTables } from "../src/data/productionTables.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "src", "generated", "productionFieldMap.ts");

const q = (s: string) => JSON.stringify(s);

// Guard the same invariants gen-stage-map.ts guards, at generation time.
const seenModels = new Set<string>();
const seenIds = new Set<string>();
for (const t of productionTables) {
  if (seenIds.has(t.id)) throw new Error(`duplicate table id: ${t.id}`);
  seenIds.add(t.id);
  if (seenModels.has(t.model)) throw new Error(`duplicate Prisma model name: ${t.model} (table ${t.id})`);
  seenModels.add(t.model);
  if (!t.sourceNodeIds.length) throw new Error(`${t.id} has no sourceNodeIds — every table must trace to a flow node`);

  const cols = new Set<string>();
  for (const f of t.fields) {
    if (!f.col) throw new Error(`${t.id} / "${f.n}" has no col`);
    if (Buffer.byteLength(f.col) > 63) throw new Error(`${t.id}.${f.col} exceeds Postgres' 63-byte identifier limit`);
    if (cols.has(f.col)) throw new Error(`${t.id} reuses col "${f.col}" — cols must be unique per table`);
    cols.add(f.col);
  }
}

const fieldCount = productionTables.reduce((n, t) => n + t.fields.length, 0);

const body = `// GENERATED by scripts/gen-production-map.ts — do not edit. Run \`npm run gen\` after changing
// productionStages.ts or productionTables.ts; \`npm run gen:check\` fails CI if this file is stale.
//
// ${productionTables.length} storage tables, ${fieldCount} (tableId, label) pairs, transcribed
// from 78 production flow nodes.

export interface ProductionFieldEntry { label: string; col: string }

export interface ProductionTableSpec {
  tableId: string;
  model: string;
  spine: "btm" | "bin" | "lot" | "standalone";
  cardinality: "one" | "many";
  sourceNodeIds: string[];
  fields: ProductionFieldEntry[];
}

export const PRODUCTION_FIELD_MAP: Record<string, ProductionTableSpec> = {
${productionTables
  .map((t) => {
    const fields = t.fields.map((f) => `      { label: ${q(f.n)}, col: ${q(f.col)} },`).join("\n");
    return `  ${q(t.id)}: {
    tableId: ${q(t.id)},
    model: ${q(t.model)},
    spine: ${q(t.spine)},
    cardinality: ${q(t.cardinality)},
    sourceNodeIds: [${t.sourceNodeIds.map(q).join(", ")}],
    fields: [
${fields}
    ],
  },`;
  })
  .join("\n")}
};

export const PRODUCTION_TABLE_IDS: string[] = [${productionTables.map((t) => q(t.id)).join(", ")}];

/** label -> col for one table. Throws on an unknown label so a typo can't silently no-op a write. */
export function productionColFor(tableId: string, label: string): string {
  const spec = PRODUCTION_FIELD_MAP[tableId];
  if (!spec) throw new Error(\`Unknown production table "\${tableId}"\`);
  const f = spec.fields.find((x) => x.label === label);
  if (!f) throw new Error(\`Unknown field "\${label}" on production table "\${tableId}"\`);
  return f.col;
}
`;

const check = process.argv.includes("--check");
if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("productionFieldMap.ts is STALE — run `npm run gen` and commit the result.");
    process.exit(1);
  }
  console.log(`productionFieldMap.ts up to date (${productionTables.length} tables, ${fieldCount} fields).`);
} else {
  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT} — ${productionTables.length} tables, ${fieldCount} fields.`);
}
