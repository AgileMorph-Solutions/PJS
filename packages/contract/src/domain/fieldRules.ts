export interface FieldIssue {
  stageId: string;
  /** The field the message is shown under. */
  label: string;
  message: string;
  /** Every field the issue is about (both weights of "empty truck heavier than loaded"). */
  involves: readonly (readonly [stageId: string, label: string])[];
}

export interface NumberRule {
  /** Whole numbers only (bags, nut count). */
  integer?: boolean;
  /** Warn below this / above this: outside what can physically be true, most likely a typing slip. */
  min?: number;
  max?: number;
  /** Warn at exactly 0 or less (a weight or price of 0 means "not weighed", not a reading). */
  positive?: boolean;
  /** WARN above / below, with the reason the person reads. */
  warnAbove?: [limit: number, why: string];
  warnBelow?: [limit: number, why: string];
  /**
   * WARN outside this: the usual range of the measure in the client's 2026 workbooks (data/fieldRanges.ts, generated by
   * tools/derive-field-ranges.py; 26 Nov 2026, user: every field gets a range from the Excel files). Only a warning.
   */
  usual?: Pick<UsualRange, "min" | "max">;
  unit?: string;
}

interface FormatRule {
  pattern: RegExp;
  /** What a right value looks like, shown in the message. */
  example: string;
}

type Rule = { number: NumberRule } | { format: FormatRule };

// Ivorian number plates, as the Bouaké offloading report (sheet DISCHARGEMENT, 454 trucks) actually has them.
// Old style: 1–4 digits, 2 letters, 2-digit region (827KT01). New style: 2 letters, 3 digits, 2 letters, region
// (AA-459-KL-03). People type spaces, dashes or nothing between the parts, so all three are fine. A truck with a
// trailer has two plates joined by "/". What's left over in the report is mostly a slip (a plate with no region,
// a trailing "/"), plus a few real oddities (temporary WW plates, a foreign plate) — hence a warning, never a stop.
const SEP = "[ -]*";
const OLD_PLATE = `\\d{1,4}${SEP}[A-Z]{2}${SEP}\\d{2}`;
const NEW_PLATE = `[A-Z]{2}${SEP}\\d{3}${SEP}[A-Z]{2}${SEP}\\d{2}`;
const PLATE = `(?:${OLD_PLATE}|${NEW_PLATE})`;
const VEHICLE_NO_PATTERN = new RegExp(`^${PLATE}(?: */ *${PLATE})?$`, "i");

const U = USUAL_RANGES;
/** A usual range scaled by a factor: a truck's pallets from its bags (30 a pallet), triage tonnes from kilograms. */
const scaled = (r: { min: number; max: number }, by: number) => ({ min: Math.floor(r.min * by), max: Math.ceil(r.max * by) });

