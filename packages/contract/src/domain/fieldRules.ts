/**
 * What a warning calls a field: its plain name above, else the label the form shows, without the unit or the panel ("Truck
 * sampling – Shell (g)" → "Shell": the warning already sits under that panel's field).
 */
export function fieldName(stageId: string, label: string): string {
  const named = FIELD_NAMES[stageId]?.[label];
  if (named) return named;
  const shown = stages.find((s) => s.id === stageId)?.fields.find((f) => f.n === label)?.label ?? label;
  return shown
    .replace(/^(Truck sampling|Final unloading) – /, "")
    .replace(/, (bags|MT)$/, "")
    .replace(/\s*\([^)]*\)$/, "");
}

/**
 * A field's name for a table's column heading (26 Nov 2026, user: "minimize the heading"): its plain name (fieldName), with
 * its unit kept when the label has one, short — "Activity type", "Re-bagging (bags)", "Triage (MT)", "Loaded truck weight
 * (kg)". The full label stays on the form.
 */
export function fieldShortLabel(stageId: string, label: string): string {
  const shown = stages.find((s) => s.id === stageId)?.fields.find((f) => f.n === label)?.label ?? label;
  const unit = /, (bags|MT)$/.exec(shown)?.[1] ?? /\((%|g|kg|MT)\)$/.exec(shown)?.[1];
  const name = fieldName(stageId, label);
  return unit ? `${name} (${unit})` : name;
}

/** The issue with one value on its own, or undefined when it is fine (or blank: blank is "not recorded yet", never wrong). */
export function checkValue(stageId: string, label: string, raw: string | undefined): Omit<FieldIssue, "involves"> | undefined {
  const value = (raw ?? "").trim();
  const rule = fieldRule(stageId, label);
  if (!rule || value === "") return undefined;
  const at = (message: string) => ({ stageId, label, message });
  const name = fieldName(stageId, label);

  if ("format" in rule) {
    const f = rule.format;
    if (f.pattern.test(value)) return undefined;
    return at(`${name} "${value}" doesn't look right. It should look like ${f.example}.`);
  }
  const problem = numberProblem(rule.number, value, name);
  return problem ? at(problem.message) : undefined;
}

/**
 * What is wrong with a typed number under one rule, or undefined: the check every numeric field uses, a stage's or not
 * (sun drying's sample readings reuse it, domain/sunDrying.ts). `soft` marks a warnAbove / warnBelow — likely but possible —
 * apart from a value that can't be right (not a number, outside min / max). Blank is the caller's: nothing to check.
 * Given the field's `name`, the message says which field it is about ("Shell is below 100 g. Please check.").
 */
export function numberProblem(r: NumberRule, raw: string | undefined, name?: string): { message: string; soft: boolean } | undefined {
  const value = (raw ?? "").trim();
  if (!value) return undefined;
  const hard = (message: string) => ({ message, soft: false });
  const soft = (message: string) => ({ message, soft: true });
  const n = parseQty(value);
  if (n === undefined) return hard(name ? `${name} must be a number, not "${value}".` : `"${value}" isn't a number.`);
  if (r.integer && !Number.isInteger(n)) return hard(name ? `${name} must be a whole number.` : "Not a whole number.");
  if (r.positive && n <= 0) return hard(name ? `${name} should be more than 0.` : "Should be more than 0.");
  const below = (limit: number) => `${name ? `${name} is below` : "Below"} ${withUnit(limit, r.unit)}`;
  const above = (limit: number) => `${name ? `${name} is above` : "Above"} ${withUnit(limit, r.unit)}`;
  if (r.min !== undefined && n < r.min) return hard(`${below(r.min)}. Please check.`);
  if (r.max !== undefined && n > r.max) return hard(`${above(r.max)}. Please check.`);
  if (r.warnAbove && n > r.warnAbove[0]) return soft(`${above(r.warnAbove[0])}: ${r.warnAbove[1]}.`);
  if (r.warnBelow && n < r.warnBelow[0]) return soft(`${below(r.warnBelow[0])}: ${r.warnBelow[1]}.`);
  if (r.usual && (n < r.usual.min || n > r.usual.max)) {
    const range = `${fmt(r.usual.min)}–${withUnit(r.usual.max, r.unit)}`;
    return soft(`${name ? `${name} is` : "It is"} ${n < r.usual.min ? "below" : "above"} the usual range (${range}). Please check.`);
  }
  return undefined;
}

