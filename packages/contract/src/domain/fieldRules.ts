/**
 * What a typed procurement value should look like (docs/procurement-field-rules.png, agreed with the team Nov 2026). Every
 * value is saved: a rule only warns, it never refuses or holds a value back (Nov 2026, the team: "all values can be
 * saved, just warn the user"). The warehouse decides; the app points out what looks wrong.
 *
 * Where the limits come from, so nobody mistakes them for invented tolerances:
 * - The usual range of every measure (moisture, nut count, KOR, each part of the cut test, truck load and tare, bags, refraction,
 *   price, GRN weight…) is derived from the client's 2026 workbooks, the same way for each (26 Nov 2026, user): the middle 98 %
 *   of the real readings, widened by 10 % of their spread, rounded outward. It is generated, never typed here:
 *   data/fieldRanges.ts, with the table of sources in docs/FIELD_RANGES.md. Outside it is a warning.
 * - moisture: the raw cashew trade's 10 % max for drying, a warning with its own reason. Over 100 % is impossible.
 * - a cut-test sample is 1,000 g (KOR_FACTOR in receiptMath.ts is per 1,000 g): no part can weigh more.
 * - a pallet carries 30 bags, so the pallets of a truck are its usual bags ÷ 30.
 * - Closing stock and the activity ledger's quantity have no workbook column to derive a range from: only "not negative".
 * The client is still to confirm the limits; to change one, change the rule in tools/derive-field-ranges.py and run it.
 *
 * Uploaded workbooks are judged the same way: a real data problem is reported, not refused.
 */
